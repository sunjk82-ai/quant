# 띄어쓰기 정규화 캐시
_norm_pattern = re.compile(r"[\s\-_]+")


def _normalize(text: str) -> str:
    return _norm_pattern.sub("", text.lower())


class NewsFilter:
    def __init__(self):
        self._positive = [(kw, w) for kw, w in POSITIVE_KEYWORDS]
        self._negative = [(kw, w) for kw, w in NEGATIVE_KEYWORDS]

    def score_headlines(self, headlines: list[str]) -> tuple[int, str]:
        """
        뉴스 헤드라인 리스트를 받아 (최고점수, 판정) 반환.
        판정: "호재" | "재료미확인" | "악재감지"
        """
        if not headlines:
            return 0, "재료미확인"

        best_score = None
        for headline in headlines:
            normalized = _normalize(headline)
            score = 0
            for kw, w in self._positive:
                if _normalize(kw) in normalized:
                    score += w
            for kw, w in self._negative:
                if _normalize(kw) in normalized:
                    score += w  # w는 이미 음수
            if best_score is None or score > best_score:
                best_score = score

        if best_score is None or best_score == 0:
            return 0, "재료미확인"
        elif best_score < 0:
            return best_score, "악재감지"
        else:
            return best_score, "호재"
